#!/usr/bin/env python3
"""Generate the curated practice vocabulary from a pinned CMUdict revision."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
from urllib.request import urlopen

COMMIT = "74790861f652b15e4ac49015a90074ad62a27690"
DICTIONARY_URL = f"https://raw.githubusercontent.com/cmusphinx/cmudict/{COMMIT}/cmudict.dict"
DICTIONARY_SHA256 = "81917843c7f44ce2b094ac63873c2c7a4cf802040792c455ba3ca406891c3d22"
LICENSE_SHA256 = "bd4ce8e44170a5f9f481310ca85c51de3c4f851a65e679b40e603b143bd3542a"
HERE = Path(__file__).resolve().parent
DEFAULT_OUTPUT = HERE.parents[1] / "apps/ios-learner/Sources/DirectPractice/PracticeVocabulary.swift"
PHONE_TO_SOUND = dict(zip(
    "B P M T D N K G F V S Z SH CH JH L R W Y HH TH DH NG ZH".split(),
    "b p m t d n k g f v s z sh ch j l r w y h th voiced-th ng zh".split(),
))


def read_candidates(path: Path) -> list[str]:
    words = []
    for line in path.read_text().splitlines():
        if not line.startswith("#"):
            words.extend(line.split())
    if any(not re.fullmatch(r"[a-z]+(?:-[a-z]+)*", word) for word in words):
        raise ValueError("Candidate list must contain lowercase alphabetic words only")
    return sorted(set(words))


def read_dictionary(path: Path | None) -> dict[str, list[list[str]]]:
    raw = path.read_bytes() if path else urlopen(DICTIONARY_URL, timeout=30).read()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != DICTIONARY_SHA256:
        raise ValueError(f"CMUdict SHA-256 mismatch: {actual}")
    return parse_dictionary(raw)


def parse_dictionary(raw: bytes) -> dict[str, list[list[str]]]:
    pronunciations = {}
    for line in raw.decode("latin-1").splitlines():
        parts = line.split("#", 1)[0].split()
        if len(parts) < 2:
            continue
        word, *phones = parts
        base = re.sub(r"\(\d+\)$", "", word)
        pronunciations.setdefault(base, []).append(
            [re.sub(r"[012]$", "", phone) for phone in phones]
        )
    return pronunciations


def targets(phones: list[str]) -> set[str]:
    return {
        f"{PHONE_TO_SOUND[phone]}:{'beginning' if index == 0 else 'end' if index == len(phones) - 1 else 'middle'}"
        for index, phone in enumerate(phones)
        if phone in PHONE_TO_SOUND
    }


def generate(words: list[str], pronunciations: dict[str, list[list[str]]]) -> str:
    # Preserve the existing display spelling while using CMUdict's exact entry.
    source_spellings = {"yo-yo": "yoyo"}
    missing = [word for word in words if source_spellings.get(word, word) not in pronunciations]
    if missing:
        raise ValueError("Candidates absent from CMUdict: " + ", ".join(missing))
    rows = []
    for word in words:
        source_word = source_spellings.get(word, word)
        variants = pronunciations[source_word]
        stable_targets = set.intersection(*(targets(phones) for phones in variants))
        if not stable_targets:
            raise ValueError(f"No consonant target stable across pronunciations: {word}")
        phones = "/".join(" ".join(variant) for variant in variants)
        target_keys = " ".join(sorted(stable_targets))
        rows.append(f'    ("{word}", "{source_word}", "{phones}", "{target_keys}"),')
    header = '''// Generated by docs/content/generate-practice-library.py; do not edit by hand.
// Curated word list: docs/content/practice-library-words.txt.
// Pronunciations: CMUdict commit 74790861f652b15e4ac49015a90074ad62a27690.
// CMUdict copyright and terms: docs/content/CMUDICT-LICENSE.txt.
// Targets occur in the same position in every listed pronunciation. Stress is removed.
// Display spelling "yo-yo" maps to CMUdict's exact "yoyo" entry.

import Foundation

struct PracticeVocabularyWord: Sendable {
  let word: String
  let sourceWord: String
  let pronunciations: [[String]]
  let targetKeys: [String]
}

enum PracticeVocabulary {
  static let sourceID = "cmudict:74790861f652b15e4ac49015a90074ad62a27690"

  // Retained in the compiled app as well as the source distribution.
  static let license = """
'''
    license_path = HERE / "CMUDICT-LICENSE.txt"
    license_bytes = license_path.read_bytes()
    if hashlib.sha256(license_bytes).hexdigest() != LICENSE_SHA256:
        raise ValueError("CMUdict license SHA-256 mismatch")
    header += "\n".join("  " + line for line in license_bytes.decode().splitlines()) + '''
  """

  static let words: [PracticeVocabularyWord] = raw.map { word, sourceWord, pronunciations, targetKeys in
    PracticeVocabularyWord(
      word: word,
      sourceWord: sourceWord,
      pronunciations: pronunciations.split(separator: "/").map {
        $0.split(separator: " ").map(String.init)
      },
      targetKeys: targetKeys.split(separator: " ").map(String.init)
    )
  }

  private static let raw: [(String, String, String, String)] = [
'''
    return header + "\n".join(rows) + "\n  ]\n}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dictionary-path", type=Path, help="Use a local verified copy of cmudict.dict")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Verify output without changing it")
    args = parser.parse_args()
    words = read_candidates(HERE / "practice-library-words.txt")
    pronunciations = read_dictionary(args.dictionary_path)
    source = generate(words, pronunciations)
    formatted = subprocess.run(
        ["swift", "format", "format"], input=source, text=True, capture_output=True, check=True
    ).stdout
    if args.check:
        if args.output.read_text() != formatted:
            raise ValueError(f"Generated vocabulary is out of date: {args.output}")
        print(f"Verified reproducible output for {len(words)} distinct words")
    else:
        args.output.write_text(formatted)
        print(f"Generated {len(words)} distinct words in {args.output}")


if __name__ == "__main__":
    main()
